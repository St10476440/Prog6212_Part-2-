CREATE DATABASE RaceDay

USE RaceDay

DROP TABLE Users

CREATE TABLE Venue(
VenueID VARCHAR(100) NOT NULL PRIMARY KEY,
VenueName VARCHAR(100) NOT NULL,
City VARCHAR(100) NOT NULL,
Province VARCHAR(100) NOT NULL
);

CREATE TABLE Users(
UserID VARCHAR(100) NOT NULL PRIMARY KEY,
Password VARCHAR(100) NOT NULL,
FullName VARCHAR(100) NOT NULL,
Email VARCHAR(100) NOT NULL,
Role VARCHAR(100) NOT NULL,
PhoneNumber VARCHAR(100) NOT NULL
);

CREATE TABLE Events(
EventID VARCHAR(100) NOT NULL PRIMARY KEY,
OrganiserID VARCHAR(100) NOT NULL REFERENCES Users(UserID),
VenueID VARCHAR(100) NOT NULL REFERENCES Venue(VenueID),
EventName VARCHAR(100) NOT NULL,
EventType VARCHAR(100) NOT NULL,
EventDate DATE NOT NULL
);

CREATE TABLE Categories(
CategoryID VARCHAR(100) NOT NULL PRIMARY KEY,
EventID VARCHAR(100) NOT NULL REFERENCES Events(EventID),
CategoryName VARCHAR(100) NOT NULL,
Distance VARCHAR(100) NOT NULL,
EntryFee VARCHAR(100) NOT NULL
);

CREATE TABLE Enrolments(
EnrolmentID VARCHAR(100) NOT NULL PRIMARY KEY,
ParticipantID VARCHAR(100) NOT NULL REFERENCES Users(UserID),
CategoryID VARCHAR(100) NOT NULL REFERENCES Categories(CategoryID),
RegistrationDate DATE NOT NULL
);

CREATE TABLE Results(
ResultsID VARCHAR(100) NOT NULL PRIMARY KEY,
EnrolmentID VARCHAR(100) NOT NULL REFERENCES Enrolments(EnrolmentID),
FinishTIme TIME NOT NULL,
Position VARCHAR(100) NOT NULL,
Status VARCHAR(100) NOT NULL
);

SELECT 'DATA SOURCE' + @@SERVERNAME + ';INTIAL CATALOG=' + DB_NAME() + ';INTEGRATED SECURITY= True' AS ConnectionString